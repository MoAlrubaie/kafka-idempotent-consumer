-- Runs on startup. Works on Postgres and on H2 in PostgreSQL mode.

-- Money paid out, one row per payment. event_id is deliberately NOT unique:
-- the effect itself is not idempotent, so paying twice leaves two rows.
CREATE TABLE IF NOT EXISTS payouts (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id     VARCHAR(64)  NOT NULL,
    order_id     VARCHAR(64)  NOT NULL,
    amount_cents BIGINT       NOT NULL,
    paid_at      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Events already handled. The primary key is what makes a duplicate lose.
CREATE TABLE IF NOT EXISTS processed_events (
    event_id     VARCHAR(64)  PRIMARY KEY,
    processed_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);
